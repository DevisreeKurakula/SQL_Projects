--- Display all customers
select * from customers;

--- Display only the customer name and city of every customer.
select customer_name,city from customers;

--- Find all customers who belong to Guntur.
select customer_name,city from customers where city='Guntur';

--- Display all products whose price is greater than 2000
select product_name from products where price>2000;

--- Find the total number of customers
select count(customer_name) as Total_Customers from customers;

--- Find the highest-priced product
select product_name from products where price=(select max(price) from products);

--- display all products in descending order of price
select product_name,price from products order by price desc;

--- Find the average price of all products
select product_name,avg(price) as avg_price from products group by product_name;

--- Count how many customers belong to each city
select city,count(customer_name) from customers group by city;

--- Find the total quantity sold for each product
select product_name,sum(quantity)from products,order_items 
where products.product_id=order_items.product_id group by
product_name;

--- Find the total number of orders placed by each customer
select c.customer_name,count(o.order_id) as count_orders from customers c,
orders o where c.customer_id=o.customer_id group by 
c.customer_id,c.customer_name;

--- Display each order id along with the customer name who placed it
select c.customer_name,o.order_id  from customers c left join orders o on c.customer_id=o.customer_id;

--- Display product names and their quantities for every order.
select p.product_name,sum(oi.quantity)as total_quantity from order_items oi 
right join products p on oi.product_id=p.product_id group by p.product_name,
p.product_id;

--- Display each customers name,order id and order date.
select customer_name,order_id,order_date from customers natural join orders;

--- calculate the total revenue generated by each product
select product_name,sum(quantity*price) as total_revenue from products,order_items
where products.product_id=order_items.product_id group by 
product_name;

--- find how much money each customer spent in total.
select c.customer_name,sum(oi.quantity*p.price) as total_spent from customers c
join orders o on c.customer_id=o.CUSTOMER_ID
join order_items oi on o.order_id=oi.ORDER_ID
join products p on oi.product_id=p.product_id 
group by c.customer_id,c.customer_name;

--- find the total revenue generated in each month
select o.order_date,sum(oi.quantity*p.price)as total_amount from orders O
join order_items oi on o.order_id=oi.order_id
join products p on oi.product_id=p.product_id
group by o.order_id,o.order_date;

